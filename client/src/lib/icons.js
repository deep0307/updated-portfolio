/**
 * Single place for brand/logo icon URLs.
 * Icons come from the official Simple Icons package served via jsDelivr
 * (the `cdn.simpleicons.org` host is unreliable for some icons).
 * `slug` is a Simple Icons slug — see https://simpleicons.org
 */
export const iconUrl = (slug) => `https://cdn.jsdelivr.net/npm/simple-icons/icons/${slug}.svg`;